"""Migration generation (D7): the DDL that takes a database deployed from spec v1 to the objects
of spec v2, ordered so that enforcement is never weaker than v1 nor stricter than v2 at any
point, with the lock each statement takes on the live tables.

Phases, in order:
  1. schema (one transaction): new roles, new tables (with hardening), new columns, NOT NULL
     changes, new UNIQUE constraints.
  2. constraints (one transaction): new and changed CHECKs / FKs as NOT VALID (new writes are
     checked immediately; existing rows are checked in phase 4), new transition triggers,
     replaced trigger functions.
  3. indexes (autocommit): CREATE INDEX CONCURRENTLY for new indexes.
  4. validate (autocommit, one statement per transaction): VALIDATE CONSTRAINT.  Requires the
     pre-flight report to be clean; a violating row aborts the migration here, before any
     policy changes.
  5. swap (one transaction): policy swap (drop removed and changed, create new and changed),
     revokes and grants, changed constraints renamed into place, removed constraints and
     triggers dropped.
  6. cleanup (autocommit): DROP INDEX CONCURRENTLY for removed indexes.
  7. destructive (one transaction, only with allow_destructive): DROP COLUMN, DROP TABLE.

A changed CHECK/FK keeps its name: it is added as `<name>_mls_new`, validated, and in phase 5 the
old one is dropped and the new one renamed.  Column type changes and primary-key changes are
refused (the data migration is not MLS's to generate).

Lock modes below are what Postgres 15-18 take on the affected table; tests/templates/test_locks.py
observes them (pg_locks) on every version.
"""
from __future__ import annotations

from dataclasses import dataclass, field

from mls.compile.hardening import preamble_ddl
from mls.compile.index import index_sql
from mls.compile.internal import internal_role_ddl
from mls.compile.mutations import Mutation
from mls.compile.objects import GrantObj, Objects, objects
from mls.compile.sql import q
from mls.errors import CompileError, MlsError
from mls.spec.model import Spec

# statement kind -> lock mode held on the affected table until the end of the transaction
# (None: no lock on a user table outlives the statement; GRANT/REVOKE only update catalog rows)
LOCKS: dict[str, str | None] = {
    "create role": None,
    "create table": None,
    "revoke all": None,
    "enable rls": "AccessExclusiveLock",
    "force rls": "AccessExclusiveLock",
    "add column": "AccessExclusiveLock",
    "set not null": "AccessExclusiveLock",
    "drop not null": "AccessExclusiveLock",
    "add unique": "AccessExclusiveLock",
    "add check not valid": "AccessExclusiveLock",
    "add fk not valid": "ShareRowExclusiveLock",
    "create function": None,
    "replace function": None,
    "alter function": None,
    "create trigger": "ShareRowExclusiveLock",
    "create index concurrently": "ShareUpdateExclusiveLock",
    "validate constraint": "ShareUpdateExclusiveLock",
    "drop policy": "AccessExclusiveLock",
    "create policy": "AccessExclusiveLock",
    "revoke": None,
    "grant": None,
    "drop constraint": "AccessExclusiveLock",
    "rename constraint": "AccessExclusiveLock",
    "drop trigger": "AccessExclusiveLock",
    "drop function": None,
    "drop index concurrently": "ShareUpdateExclusiveLock",
    "drop column": "AccessExclusiveLock",
    "drop table": "AccessExclusiveLock",
}
NEW_SUFFIX = "_mls_new"


@dataclass
class MStatement:
    sql: str
    kind: str
    table: str | None = None
    rule_id: str | None = None

    @property
    def lock(self) -> str | None:
        return LOCKS[self.kind]


@dataclass
class Phase:
    name: str
    transactional: bool
    description: str
    statements: list[MStatement] = field(default_factory=list)

    def add(self, sql: str, kind: str, table: str | None = None, rule_id: str | None = None) -> None:
        self.statements.append(MStatement(sql, kind, table, rule_id))


@dataclass
class Migration:
    phases: list[Phase]
    notes: list[str] = field(default_factory=list)

    @property
    def empty(self) -> bool:
        return all(not p.statements for p in self.phases)

    def sql(self) -> str:
        out = ["-- generated by mls migrate; do not edit",
               "-- run as the owner of the MLS schema, after `mls preflight` reports no violations",
               "-- (phase 4 aborts on the first violating row, before any policy changes)"]
        for n in self.notes:
            out.append(f"-- note: {n}")
        for i, ph in enumerate(self.phases, 1):
            if not ph.statements:
                continue
            mode = "one transaction" if ph.transactional else "autocommit, one statement per transaction"
            out.append(f"\n-- ==== phase {i}: {ph.name} ({mode}) ====\n-- {ph.description}")
            if ph.transactional:
                out.append("begin;")
            for st in ph.statements:
                lock = f"  -- lock: {st.lock} on {st.table}" if st.lock and st.table else ""
                tag = f"  -- {st.rule_id}" if st.rule_id else ""
                out.append(st.sql + ";" + lock + tag)
            if ph.transactional:
                out.append("commit;")
        return "\n".join(out) + "\n"

    def to_dict(self) -> dict:
        return {"notes": self.notes,
                "phases": [{"name": p.name, "transactional": p.transactional, "description": p.description,
                            "statements": [{"sql": s.sql, "kind": s.kind, "table": s.table,
                                            "lock": s.lock, "rule_id": s.rule_id} for s in p.statements]}
                           for p in self.phases]}


def _phases() -> list[Phase]:
    return [
        Phase("schema", True, "additive schema changes"),
        Phase("constraints", True, "new and changed constraints as NOT VALID; new triggers"),
        Phase("indexes", False, "CONCURRENTLY cannot run inside a transaction"),
        Phase("validate", False, "scan existing rows; short lock windows, writes continue"),
        Phase("swap", True, "policies, privileges and constraint names change atomically"),
        Phase("cleanup", False, "removed indexes"),
        Phase("destructive", True, "data-losing drops (only with --allow-destructive)"),
    ]


def _refusals(old: Spec, new: Spec, o: Objects, n: Objects) -> list[MlsError]:
    errs = []
    for name in sorted(set(o.tables) & set(n.tables)):
        ot, nt = o.tables[name], n.tables[name]
        for c in sorted(set(ot.columns) & set(nt.columns)):
            if ot.columns[c].type != nt.columns[c].type:
                errs.append(MlsError(
                    path=f"$.tables.{name}.columns.{c}.type",
                    message=f"column '{name}.{c}' changes type from {ot.columns[c].type} to "
                            f"{nt.columns[c].type}; MLS does not generate data conversions",
                    fix="add a new column, migrate the data outside MLS, then remove the old column",
                    code="migrate"))
        if ot.pk != nt.pk:
            errs.append(MlsError(
                path=f"$.tables.{name}.primary_key",
                message=f"the primary key of '{name}' changes from {list(ot.pk or [])} to {list(nt.pk or [])}",
                fix="keep the primary key; create a new table if the key must change", code="migrate"))
    if old.identity.adapter != new.identity.adapter:
        errs.append(MlsError(
            path="$.identity.adapter",
            message=f"the identity adapter changes from {old.identity.adapter} to {new.identity.adapter}; "
                    f"every policy would change meaning at once",
            fix="keep the adapter, or redeploy from scratch", code="migrate"))
    return errs


def migrate(old: Spec, new: Spec, allow_destructive: bool = False,
            mutations: frozenset[Mutation] | set[Mutation] = frozenset()) -> Migration:
    mutations = frozenset(mutations)
    o, n = objects(old), objects(new, mutations)
    errs = _refusals(old, new, o, n)
    if errs:
        raise CompileError(errs)
    ph = {p.name: p for p in _phases()}
    m = Migration(list(ph.values()))
    schema, cons, idx, val, swap, clean, destr = (ph[k] for k in
                                                 ("schema", "constraints", "indexes", "validate", "swap",
                                                  "cleanup", "destructive"))
    # ---- 1. schema
    for r in n.roles:
        if r not in o.roles:
            schema.add(f"do $mls$ begin\n  if not exists (select 1 from pg_roles where rolname = '{r}') then\n"
                       f"    create role {q(r)} nologin;\n  end if;\nend $mls$", "create role")
            schema.add(f"alter role {q(r)} nobypassrls nosuperuser nocreatedb nocreaterole", "create role")
            schema.add(f"revoke set on parameter session_replication_role from {q(r)}", "create role")
    for r in o.roles:
        if r not in n.roles:
            m.notes.append(f"role '{r}' is no longer used by the spec; roles are global and are not dropped")
    if n.internal_role and not o.internal_role:
        for s in internal_role_ddl(new):
            schema.add(s, "create role")
    from mls.compile.table import table_ddl

    for name in n.tables:
        if name in o.tables:
            continue
        for s in table_ddl(name, new.tables[name]):
            schema.add(s, "create table", name)
        schema.add(f"revoke all on {q(name)} from public", "revoke all", name)
        for r in n.roles:
            schema.add(f"revoke all on {q(name)} from {q(r)}", "revoke all", name)
        schema.add(f"alter table {q(name)} enable row level security", "enable rls", name)
        if Mutation.HARDENING_NO_FORCE not in mutations:
            schema.add(f"alter table {q(name)} force row level security", "force rls", name)
    for name in sorted(set(o.tables) & set(n.tables)):
        ot, nt = o.tables[name], n.tables[name]
        for c, col in nt.columns.items():
            if c not in ot.columns:
                nn = " not null" if col.notnull else ""
                schema.add(f"alter table {q(name)} add column {q(c)} {col.type}{nn}", "add column", name)
                if col.notnull:
                    m.notes.append(f"new NOT NULL column '{name}.{c}' has no default: the ADD COLUMN fails "
                                   f"if '{name}' has rows (pre-flight reports the row count)")
            elif ot.columns[c].notnull != col.notnull:
                if col.notnull:
                    schema.add(f"alter table {q(name)} alter column {q(c)} set not null", "set not null", name)
                else:
                    schema.add(f"alter table {q(name)} alter column {q(c)} drop not null", "drop not null", name)
        for uname, cols in nt.uniques.items():
            if uname not in ot.uniques:
                schema.add(f"alter table {q(name)} add constraint {q(uname)} unique "
                           f"({', '.join(q(c) for c in cols)})", "add unique", name)
        for uname in ot.uniques:
            if uname not in nt.uniques:
                swap.add(f"alter table {q(name)} drop constraint {q(uname)}", "drop constraint", name)
    # ---- 2. constraints (NOT VALID) and triggers; 4. validate; 5. rename into place
    for key, c in n.constraints.items():
        prev = o.constraints.get(key)
        if prev is not None and prev.definition == c.definition:
            continue
        if c.table not in o.tables:
            # new table: nothing to validate, add directly (the table is empty)
            cons.add(f"alter table {q(c.table)} add constraint {q(c.name)} {c.definition}",
                     f"add {c.kind} not valid", c.table, c.rule_id)
            continue
        tmp = c.name + NEW_SUFFIX if prev is not None else c.name
        cons.add(f"alter table {q(c.table)} add constraint {q(tmp)} {c.definition} not valid",
                 f"add {c.kind} not valid", c.table, c.rule_id)
        if Mutation.MIGRATE_SKIP_VALIDATE not in mutations:
            val.add(f"alter table {q(c.table)} validate constraint {q(tmp)}", "validate constraint",
                    c.table, c.rule_id)
        if prev is not None:
            swap.add(f"alter table {q(c.table)} drop constraint {q(c.name)}", "drop constraint", c.table, c.rule_id)
            swap.add(f"alter table {q(c.table)} rename constraint {q(tmp)} to {q(c.name)}",
                     "rename constraint", c.table, c.rule_id)
    for key, c in o.constraints.items():
        if key not in n.constraints and c.table in n.tables:
            swap.add(f"alter table {q(c.table)} drop constraint {q(c.name)}", "drop constraint", c.table, c.rule_id)
    for name, f in n.functions.items():
        prev = o.functions.get(name)
        if prev is None:
            for i, ddl in enumerate(f.create_ddl()):
                cons.add(ddl, "create function" if i == 0 else "alter function", None, f.rule_id)
        else:
            if prev.ddl != f.ddl:
                cons.add(f.replace_ddl(), "replace function", None, f.rule_id)
            if prev.owner != f.owner and f.owner:
                cons.add(f"alter function {f.signature} owner to {q(f.owner)}", "alter function", None, f.rule_id)
            if prev.execute != f.execute:
                for g in set(prev.execute) - set(f.execute):
                    swap.add(f"revoke execute on function {f.signature} from {q(g)}", "alter function", None, f.rule_id)
                for g in set(f.execute) - set(prev.execute):
                    swap.add(f"grant execute on function {f.signature} to {q(g)}", "alter function", None, f.rule_id)
    for key, t in n.triggers.items():
        prev = o.triggers.get(key)
        if prev is None:
            cons.add(t.trigger_ddl, "create trigger", t.table, t.rule_id)
        elif prev.trigger_ddl != t.trigger_ddl:
            swap.add(f"drop trigger {q(t.name)} on {q(t.table)}", "drop trigger", t.table, t.rule_id)
            swap.add(t.trigger_ddl, "create trigger", t.table, t.rule_id)
    for key, t in o.triggers.items():
        if key not in n.triggers and t.table in n.tables:
            swap.add(f"drop trigger {q(t.name)} on {q(t.table)}", "drop trigger", t.table, t.rule_id)
    # ---- 3. indexes; 6. cleanup
    for key, ix in n.indexes.items():
        if key not in o.indexes:
            if ix.table in o.tables:
                idx.add(index_sql(ix.name, ix.table, ix.columns, concurrently=True),
                        "create index concurrently", ix.table)
            else:
                schema.add(index_sql(ix.name, ix.table, ix.columns), "create table", ix.table)
    for key, ix in o.indexes.items():
        if key not in n.indexes and ix.table in n.tables:
            clean.add(f"drop index concurrently {q(ix.name)}", "drop index concurrently", ix.table)
    # ---- 5. swap: policies and grants
    for key, p in o.policies.items():
        np_ = n.policies.get(key)
        if p.table in n.tables and (np_ is None or np_.ddl != p.ddl):
            swap.add(f"drop policy {q(p.name)} on {q(p.table)}", "drop policy", p.table, p.rule_id)
    for key, p in n.policies.items():
        prev = o.policies.get(key)
        if prev is None or prev.ddl != p.ddl:
            swap.add(p.ddl, "create policy", p.table, p.rule_id)
    for g in sorted(o.grants - n.grants, key=lambda g: (g.table, g.role, g.command)):
        if g.table in n.tables:
            swap.add(g.sql("revoke"), "revoke", g.table)
    for g in sorted(n.grants - o.grants, key=lambda g: (g.table, g.role, g.command)):
        swap.add(g.sql("grant"), "grant", g.table)
    # ---- 7. destructive
    for name in sorted(set(o.tables) & set(n.tables)):
        for c in o.tables[name].columns:
            if c not in n.tables[name].columns:
                destr.add(f"alter table {q(name)} drop column {q(c)}", "drop column", name)
    for name in o.tables:
        if name not in n.tables:
            destr.add(f"drop table {q(name)}", "drop table", name)
    # removed helper functions go after the policies that reference them (swap), or after the
    # dropped tables whose policies reference them (destructive)
    for name, f in o.functions.items():
        if name not in n.functions:
            used_by_dropped = any(p.table not in n.tables and q(name) in p.ddl for p in o.policies.values())
            (destr if used_by_dropped else swap).add(f"drop function {f.signature}", "drop function", None, f.rule_id)
    if not m.empty:  # the owner guard comes first
        schema.statements.insert(0, MStatement(preamble_ddl(new)[0], "create table"))
    if destr.statements and not allow_destructive:
        kept = [s.sql for s in destr.statements]
        destr.statements = []
        m.notes.append("destructive statements omitted (pass --allow-destructive to include them): "
                       + "; ".join(kept))
    return m
