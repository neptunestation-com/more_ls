"""mls: check | prove | compile | test | diff | migrate | preflight | drift | import | status | explain | fmt | lint | schema | eval"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from mls.errors import CompileError, SpecError


def _load(path: str):
    from mls.spec import load_checked

    return load_checked(path)


def _print_errors(e: Exception, as_json: bool) -> None:
    errors = getattr(e, "errors", [])
    if as_json:
        print(json.dumps({"ok": False, "errors": [x.to_dict() for x in errors]}, indent=2))
    else:
        for x in errors:
            print(str(x), file=sys.stderr)


def cmd_check(a) -> int:
    try:
        spec = _load(a.spec)
    except (SpecError, CompileError) as e:
        _print_errors(e, a.json)
        return 1
    from mls.compile.plan import soundness_errors

    errs = soundness_errors(spec)
    if not errs and a.dsn:  # D45: adopted tables are checked against the catalog
        import psycopg

        from mls.pg.adopt import verify_adopted

        with psycopg.connect(a.dsn) as conn:
            errs = verify_adopted(conn, spec, schema=a.schema)
    if errs:
        from mls.spec import locate

        _print_errors(CompileError(locate(a.spec, errs)), a.json)
        return 1
    print(json.dumps({"ok": True}) if a.json else f"{a.spec}: OK")
    return 0


def cmd_fmt(a) -> int:
    """Convert between the two syntaxes (D50); `fmt` of a .mls file to terse is the formatter."""
    from mls.spec import is_terse, load_spec, spec_to_json
    from mls.terse import render

    try:
        spec = load_spec(a.spec)
    except SpecError as e:
        _print_errors(e, False)
        return 1
    to = a.to or ("json" if is_terse(a.spec) else "terse")
    text = render(spec) if to == "terse" else spec_to_json(spec)
    if a.out:
        Path(a.out).write_text(text)
    else:
        print(text, end="")
    return 0


def cmd_schema(a) -> int:
    from mls.spec import spec_json_schema

    print(json.dumps(spec_json_schema(), indent=2))
    return 0


def cmd_prove(a) -> int:
    from mls.props.report import dumps_json, to_markdown
    from mls.props.runner import run_all

    try:
        spec = _load(a.spec)
    except SpecError as e:
        _print_errors(e, a.format == "json")
        return 1
    results = run_all(spec, timeout_ms=a.timeout * 1000)
    out = dumps_json(spec, results) if a.format == "json" else to_markdown(spec, results)
    if a.out:
        Path(a.out).write_text(out)
    else:
        print(out)
    return 0 if all(r.verdict == "PROVED" for r in results) else 2


def cmd_compile(a) -> int:
    from mls.compile import compile_spec

    try:
        spec = _load(a.spec)
        script = compile_spec(spec)
    except (SpecError, CompileError) as e:
        _print_errors(e, False)
        return 1
    header = "-- generated by mls compile; do not edit\n-- assumptions:\n" + \
        "".join(f"--   {x}\n" for x in script.assumptions)
    out = header + script.sql()
    if a.out:
        Path(a.out).write_text(out)
    else:
        print(out)
    return 0


def cmd_lint(a) -> int:
    from mls.pg.lint import lint_catalog, lint_static
    from mls.props.lint import lint_spec

    try:
        spec = _load(a.spec)
    except SpecError as e:
        _print_errors(e, a.json)
        return 1
    if a.dsn:
        import psycopg

        with psycopg.connect(a.dsn) as conn:
            warnings = lint_catalog(spec, conn)
    else:
        warnings = lint_static(spec)
    findings = lint_spec(spec, timeout_ms=a.timeout * 1000)  # D49: hygiene, never verdicts
    if a.json:
        print(json.dumps({"warnings": [{"table": w.table, "column": w.column, "type": w.type,
                                        "operators": w.operators, "message": str(w)} for w in warnings],
                          "findings": [f.to_dict() for f in findings]}, indent=2))
        return 0
    for w in warnings:
        print(f"warning: {w}")
    for f in findings:
        print(str(f))
    print(f"{len(warnings)} warning(s), {len(findings)} finding(s)")
    return 0


def cmd_test(a) -> int:
    from mls.compile import compile_spec
    from mls.pg.harness import run_differential
    from mls.pg.server import PG_VERSIONS, postgres_container

    try:
        spec = _load(a.spec)
        script = compile_spec(spec)
    except (SpecError, CompileError) as e:
        _print_errors(e, False)
        return 1

    def run(dsn: str, label: str) -> bool:
        res = run_differential(spec, script, dsn, a.dbname, seed=a.seed, rows_per_table=a.rows,
                               n_contexts=a.contexts, ops_per_context=a.ops)
        print(f"[{label}] differential: {res.summary()}")
        for m in res.mismatches[:10]:
            print(f"  MISMATCH {m}")
        ok = res.ok
        if a.explain:
            ok = _explain(spec, script, dsn, label, a.scale) and ok
        return ok

    ok = True
    if a.dsn:
        ok = run(a.dsn, "dsn")
    else:
        versions = a.versions.split(",") if a.versions else list(PG_VERSIONS)
        for v in versions:
            with postgres_container(v) as dsn:
                ok = run(dsn, f"pg{v}") and ok
    return 0 if ok else 1


def _explain(spec, script, dsn: str, label: str, scale: int) -> bool:
    import psycopg
    from psycopg import sql as psql

    from mls.compile.plan import Script
    from mls.pg.explain import explain_checks, scale_load_sql
    from mls.pg.harness import Harness, ValueGen
    import random

    skinny = Script([s for s in script.statements if s.section not in ("checks", "fks", "transitions", "cardinalities")],
                    script.assumptions)
    h = Harness(spec, skinny, dsn, "mls_explain")
    try:
        h.deploy()
        with h.conn.cursor() as cur:
            for s in scale_load_sql(spec, h.adapter, scale):
                cur.execute(s)
        gen = ValueGen(spec, h.adapter, random.Random(0), n_users=100)
        results = explain_checks(h.conn, spec, h.adapter, lambda role: gen.context(role))
    finally:
        h.close()
    ok = True
    for r in results:
        print(f"[{label}] explain {r.table} as {r.role}: {'ok' if r.ok else 'FAIL ' + '; '.join(r.problems)}")
        ok = ok and r.ok
    return ok


def cmd_explain(a) -> int:
    from mls.english import spec_summary
    from mls.terse import spec_listing

    try:
        spec = _load(a.spec)
    except SpecError as e:
        _print_errors(e, False)
        return 1
    print(spec_listing(spec) if a.terse else spec_summary(spec), end="")
    return 0


def cmd_diff(a) -> int:
    from mls.props.diff import diff, to_json, to_markdown

    try:
        old, new = _load(a.old), _load(a.new)
    except SpecError as e:
        _print_errors(e, a.format == "json")
        return 1
    d = diff(old, new, timeout_ms=a.timeout * 1000)
    out = json.dumps(to_json(old, new, d), indent=2, default=str) if a.format == "json" else to_markdown(old, new, d)
    if a.out:
        Path(a.out).write_text(out)
    else:
        print(out, end="")
    return 2 if d.any_change else 0


def cmd_migrate(a) -> int:
    from mls.compile.migrate import migrate
    from mls.compile.plan import soundness_errors

    try:
        old, new = _load(a.old), _load(a.new)
        errs = soundness_errors(new)
        if errs:
            raise CompileError(errs)
        m = migrate(old, new, allow_destructive=a.allow_destructive)
    except (SpecError, CompileError) as e:
        _print_errors(e, a.format == "json")
        return 1
    out = json.dumps(m.to_dict(), indent=2) if a.format == "json" else m.sql()
    if a.out:
        Path(a.out).write_text(out)
    else:
        print(out, end="")
    return 0


def cmd_preflight(a) -> int:
    import psycopg

    from mls.pg.preflight import preflight

    try:
        new = _load(a.new)
        old = _load(a.old) if a.old else None
    except SpecError as e:
        _print_errors(e, a.json)
        return 1
    with psycopg.connect(a.dsn) as conn:
        res = preflight(conn, new, old, schema=a.schema, samples=a.samples)
    if a.json:
        print(json.dumps({"ok": res.ok, "notes": res.notes,
                          "violations": [{"rule": v.rule_id, "table": v.table, "what": v.what, "count": v.count,
                                          "samples": v.samples, "sql": v.sql} for v in res.violations]},
                         indent=2, default=str))
    else:
        for n in res.notes:
            print(f"note: {n}")
        for v in res.violations:
            print(str(v))
        print("pre-flight: " + ("OK, no existing row violates the new constraints" if res.ok
                                else f"{len(res.violations)} violation group(s)"))
    return 0 if res.ok else 1


def cmd_drift(a) -> int:
    import psycopg

    from mls.compile import compile_spec
    from mls.pg.drift import drift

    try:
        spec = _load(a.spec)
        script = compile_spec(spec)
    except (SpecError, CompileError) as e:
        _print_errors(e, a.json)
        return 1
    with psycopg.connect(a.dsn) as conn:
        res = drift(conn, spec, script, schema=a.schema)
    if a.json:
        print(json.dumps({"ok": res.ok, "notes": res.notes,
                          "drift": [{"kind": i.kind, "object": i.object, "expected": i.expected, "actual": i.actual}
                                    for i in res.items]}, indent=2, default=str))
    else:
        for n in res.notes:
            print(f"note: {n}")
        for i in res.items:
            print(str(i))
        failing = [i for i in res.items if i.kind not in ("assumed", "foreign")]
        extra = ", ".join(f"{len(res.by_kind(k))} {k}" for k in ("assumed", "foreign") if res.by_kind(k))
        print("drift: " + ("none, the live schema matches the spec" if res.ok else f"{len(failing)} item(s)")
              + (f" ({extra})" if extra else ""))
    return 0 if res.ok else 1


def cmd_status(a) -> int:
    from mls.props.runner import run_all
    from mls.status import failing, table_statuses, to_json, to_text

    try:
        spec = _load(a.spec)
    except (SpecError, CompileError) as e:
        _print_errors(e, a.json)
        return 1
    results = run_all(spec, timeout_ms=a.timeout * 1000)
    snap = None
    if a.dsn:
        import psycopg

        from mls.pg.catalog import snapshot
        from mls.pg.drift import _observed, _roles

        with psycopg.connect(a.dsn) as conn:
            snap = snapshot(conn, a.schema, list(spec.governed()), _roles(spec), _observed(spec))
    statuses = table_statuses(spec, results, snap)
    print(json.dumps(to_json(statuses), indent=2) if a.json else to_text(statuses))
    return 2 if failing(statuses) else 0


def cmd_import(a) -> int:
    import psycopg

    from mls.pg.adopt import import_schema

    try:
        with psycopg.connect(a.dsn) as conn:
            res = import_schema(conn, schema=a.schema, roles=a.role or None)
    except SpecError as e:
        _print_errors(e, a.json)
        return 1
    text = json.dumps(res.spec, indent=1) + "\n"
    if a.out:
        Path(a.out).write_text(text)
    if a.json:
        print(json.dumps({"ok": True, "spec": res.spec, "notes": res.notes}, indent=1))
    else:
        for n in res.notes:
            print(f"note: {n}", file=sys.stderr)
        if not a.out:
            print(text, end="")
        else:
            print(f"{a.out}: imported {len(res.spec['tables'])} table(s), {len(res.notes)} note(s)", file=sys.stderr)
    return 0


def cmd_eval(a) -> int:
    from mls.evals import case_files, generation_case, load_case, run_cases, run_llm_case, synthetic_cases

    paths = [Path(p) for p in a.cases]
    if a.mutate:
        total_written, total_missed = 0, 0
        for f in case_files(paths):
            if load_case(f).get("origin") == "synthetic":
                continue  # mutants of mutants are not cases; the command is idempotent over its own output
            written, missed = synthetic_cases(f, Path(a.mutate))
            total_written += len(written)
            total_missed += len(missed)
            print(f"{f.stem}: {len(written)} detected mutant(s) written, {len(missed)} undetected"
                  + (f" ({', '.join(missed)})" if missed else ""))
        caught = total_written + total_missed
        score = f"{total_written / caught:.0%}" if caught else "n/a"
        print(f"mutation score of the property sets: {score} ({total_written}/{caught})")
        return 0
    if a.llm:
        from mls.llm.client import client_from_env
        from mls.llm.grade import summarize

        from mls.llm.grade import CaseGrade, expected_status

        grades = []
        for f in case_files(paths):
            case = load_case(f)
            why = generation_case(case, a.repair)
            if why:
                print(f"skip: {case['id']} — {why}")
                continue
            client = client_from_env(a.model, a.effort)
            try:
                g, result = run_llm_case(f, client, a.max_repairs, repair_from_reference=a.repair)
            except Exception as e:  # noqa: BLE001 - one case must not end the run
                g = CaseGrade(case["id"], expected_status(case), "failed", False, False, False,
                              differences=[f"{type(e).__name__}: {e}"])
                result = None
            grades.append(g)
            mark = "ok" if g.correct else "FAIL"
            print(f"{mark}: {g.case_id} — {g.status} (expected {g.expected_status}), "
                  f"{g.repair_rounds} repair round(s), net_equivalent={g.net_equivalent}, "
                  f"reference_properties_hold={g.reference_properties_hold}"
                  + (f"; {'; '.join(g.net_differences[:3])}" if g.net_differences else "")
                  + (f"; {'; '.join(g.differences[:2])}" if result is None and g.differences else ""))
            if result is None:
                continue
            if a.transcripts:
                d = Path(a.transcripts)
                d.mkdir(parents=True, exist_ok=True)
                (d / f"{g.case_id}.json").write_text(json.dumps(
                    {"grade": g.to_dict(), "result": result.to_dict(),
                     "spec_terse": _terse_lines(result.spec),
                     "exchanges": [{"name": x.request.name, "user": x.request.user, "response": x.response,
                                    "usage": x.usage} for x in getattr(client, "exchanges", [])]},
                    indent=1, default=str))
        summary = summarize(grades)
        print(json.dumps(summary, indent=1) if a.json else
              "\n".join(f"{k}: {v}" for k, v in summary.items()))
        return 0 if all(g.correct for g in grades) else 1
    results = run_cases(paths)
    bad = 0
    for r in results:
        status = "ok" if r.ok else "FAIL"
        print(f"{status}: {r.case_id} — {r.message}")
        bad += 0 if r.ok else 1
    return 0 if bad == 0 else 1


def _terse_lines(spec) -> list[str] | None:
    """The generated spec, one line per rule and property (D44), for reading a transcript."""
    from mls.terse import spec_listing

    return spec_listing(spec).rstrip("\n").split("\n") if spec is not None else None


def cmd_generate(a) -> int:
    from mls import english
    from mls.llm.client import client_from_env
    from mls.llm.loop import generate
    from mls.llm.schemas import skeleton_of

    requirements = sys.stdin.read() if a.requirements == "-" else Path(a.requirements).read_text()
    skeleton = skeleton_of(json.loads(Path(a.skeleton).read_text()))
    client = client_from_env(a.model, a.effort)
    result = generate(requirements, skeleton, client, a.max_repairs)
    if a.transcript:
        Path(a.transcript).write_text(json.dumps(
            {"result": result.to_dict(), "spec_terse": _terse_lines(result.spec),
             "exchanges": [{"name": x.request.name, "system": x.request.system, "user": x.request.user,
                            "response": x.response, "usage": x.usage} for x in getattr(client, "exchanges", [])]},
            indent=1, default=str))
    if a.out and result.spec is not None:
        Path(a.out).write_text(json.dumps(result.spec.model_dump(by_alias=True, exclude_none=True), indent=1) + "\n")
    if a.json:
        print(json.dumps(result.to_dict(), indent=1, default=str))
        return 0 if result.status == "proved" else 1
    print(f"status: {result.status} after {result.repair_rounds} repair round(s)")
    for st in result.steps:
        print(f"  {st.stage}: {st.detail}")
    if result.spec is not None:
        print("\n# Properties (for approval)")
        for p in result.spec.properties:
            print(f"- {p.id} ({result.verdicts.get(p.id, '?')}): {english.prop(result.spec, p)}")
    if result.errors:
        print("\n# Errors")
        for e in result.errors:
            print(f"- {e}")
    if result.escalations:
        print("\n# Needs a human decision (the rules and a property disagree)")
        for e in result.escalations:
            print(f"- {e}")
    for k, v in result.notes.items():
        print(f"\nnotes from the {k} pass: {v}")
    return 0 if result.status == "proved" else 1


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="mls", description=__doc__)
    sub = ap.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("check", help="validate, typecheck and fragment-check a spec")
    p.add_argument("spec")
    p.add_argument("--dsn", help="also verify the adopted tables against this database's catalog (D45)")
    p.add_argument("--schema", default="public")
    p.add_argument("--json", action="store_true")
    p.set_defaults(fn=cmd_check)

    p = sub.add_parser("fmt", help="convert a spec between the JSON and the terse syntax (D50); the other syntax "
                                   "by default, `--to terse` on a .mls file formats it")
    p.add_argument("spec")
    p.add_argument("--to", choices=["json", "terse"])
    p.add_argument("--out")
    p.set_defaults(fn=cmd_fmt)

    p = sub.add_parser("schema", help="print the JSON Schema of the spec language")
    p.set_defaults(fn=cmd_schema)

    p = sub.add_parser("prove", help="prove the spec's properties")
    p.add_argument("spec")
    p.add_argument("--format", choices=["md", "json"], default="md")
    p.add_argument("--out")
    p.add_argument("--timeout", type=int, default=20, help="seconds per obligation")
    p.set_defaults(fn=cmd_prove)

    p = sub.add_parser("compile", help="compile the spec to DDL")
    p.add_argument("spec")
    p.add_argument("--out")
    p.set_defaults(fn=cmd_compile)

    p = sub.add_parser("lint", help="leakproof lint and policy-set hygiene (coverage, contradiction, subsumption, "
                                    "redundancy; findings, never verdicts)")
    p.add_argument("spec")
    p.add_argument("--dsn")
    p.add_argument("--timeout", type=int, default=20, help="per-question solver timeout in seconds")
    p.add_argument("--json", action="store_true")
    p.set_defaults(fn=cmd_lint)

    p = sub.add_parser("test", help="differential test against real Postgres (Docker or --dsn)")
    p.add_argument("spec")
    p.add_argument("--dsn", help="superuser DSN; without it, Docker containers are started")
    p.add_argument("--versions", help="comma-separated Postgres major versions (default 15,16,17,18)")
    p.add_argument("--dbname", default="mls_difftest")
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--rows", type=int, default=25)
    p.add_argument("--contexts", type=int, default=12)
    p.add_argument("--ops", type=int, default=20)
    p.add_argument("--explain", action="store_true", help="also run EXPLAIN checks at --scale rows")
    p.add_argument("--scale", type=int, default=1_000_000)
    p.set_defaults(fn=cmd_test)

    p = sub.add_parser("explain", help="render the rules and properties in plain English")
    p.add_argument("spec")
    p.add_argument("--terse", action="store_true",
                   help="the terse one-line-per-item rendering instead of English (for reading, not input)")
    p.set_defaults(fn=cmd_explain)

    p = sub.add_parser("diff", help="access diff between two spec versions, with scenarios")
    p.add_argument("old")
    p.add_argument("new")
    p.add_argument("--format", choices=["md", "json"], default="md")
    p.add_argument("--out")
    p.add_argument("--timeout", type=int, default=20, help="seconds per obligation")
    p.set_defaults(fn=cmd_diff)

    p = sub.add_parser("migrate", help="DDL that takes a database from the old spec to the new one")
    p.add_argument("old")
    p.add_argument("new")
    p.add_argument("--format", choices=["sql", "json"], default="sql")
    p.add_argument("--out")
    p.add_argument("--allow-destructive", action="store_true", help="include DROP COLUMN / DROP TABLE")
    p.set_defaults(fn=cmd_migrate)

    p = sub.add_parser("preflight", help="count existing rows the new spec's constraints would reject")
    p.add_argument("new")
    p.add_argument("--old", help="the deployed spec (only new or changed constraints are checked)")
    p.add_argument("--dsn", required=True)
    p.add_argument("--schema", default="public")
    p.add_argument("--samples", type=int, default=5)
    p.add_argument("--json", action="store_true")
    p.set_defaults(fn=cmd_preflight)

    p = sub.add_parser("drift", help="compare the live catalog with a shadow deploy of the spec")
    p.add_argument("spec")
    p.add_argument("--dsn", required=True)
    p.add_argument("--schema", default="public")
    p.add_argument("--json", action="store_true")
    p.set_defaults(fn=cmd_drift)

    p = sub.add_parser("status", help="governance status per table: ungoverned, refuted, opaque, unproved or proved")
    p.add_argument("spec")
    p.add_argument("--dsn", help="also read the live catalog: RLS state, missing tables, tables outside the spec")
    p.add_argument("--schema", default="public")
    p.add_argument("--timeout", type=int, default=20, help="per-obligation solver timeout in seconds")
    p.add_argument("--json", action="store_true")
    p.set_defaults(fn=cmd_status)

    p = sub.add_parser("import", help="write a spec from a live schema: tables adopted, policies lifted into the "
                                      "fragment where the lifter reads them, opaque otherwise (D45, D46)")
    p.add_argument("--dsn", required=True)
    p.add_argument("--schema", default="public")
    p.add_argument("--role", action="append", help="app role (repeatable); default: the roles the policies and grants name")
    p.add_argument("--out", help="write the spec here (default: stdout); the notes go to stderr")
    p.add_argument("--json", action="store_true", help="print {spec, notes} as JSON")
    p.set_defaults(fn=cmd_import)

    p = sub.add_parser("eval", help="run eval cases (expected verdicts of reference specs; --llm runs the loop)")
    p.add_argument("cases", nargs="+")
    p.add_argument("--llm", action="store_true", help="generate specs from the requirements with the LLM loop and grade them")
    p.add_argument("--repair", action="store_true", help="with --llm: start from the case's reference rules (repair benchmark)")
    p.add_argument("--mutate", metavar="DIR", help="write solver-graded synthetic mutants of the cases to DIR")
    p.add_argument("--model", default="claude-opus-5-5")
    p.add_argument("--effort", default="high")
    p.add_argument("--max-repairs", type=int, default=3)
