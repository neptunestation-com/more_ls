-- A typical Supabase starter (ROADMAP Milestone 6, D52): what a project looks like before a
-- takeover.  Profiles keyed by auth.users, bigint identity keys, a membership table, tables
-- nested two deep under it (tasks -> projects -> teams), the two half-hearted policies of the
-- dashboard's profile template, one table without RLS, one view, one SECURITY DEFINER function.
-- Loaded as Supabase's `postgres` role into a database prepared like a project's (auth schema,
-- default privileges).  `mls import --policies discard` reads it into a skeleton.

create table profiles (
  id uuid primary key references auth.users on delete cascade,
  username text unique,
  full_name varchar(100),
  avatar_url text,
  updated_at timestamptz
);
alter table profiles enable row level security;
create policy "Public profiles are viewable by everyone." on profiles for select using (true);
create policy "Users can update own profile." on profiles for update using ((select auth.uid()) = id);

create table teams (
  id bigint generated by default as identity primary key,
  name text not null,
  created_at timestamptz not null default now()
);
alter table teams enable row level security;

-- the membership table: no RLS, as it is usually left
create table team_members (
  team_id bigint not null references teams on delete cascade,
  user_id uuid not null references auth.users on delete cascade,
  role text not null default 'member',
  primary key (team_id, user_id),
  check (role in ('owner', 'member'))
);

create table projects (
  id bigint generated by default as identity primary key,
  team_id bigint not null references teams on delete cascade,
  name text not null,
  archived boolean not null default false,
  settings jsonb not null default '{}'
);
alter table projects enable row level security;
create index on projects (team_id);

create table tasks (
  id bigint generated by default as identity primary key,
  project_id bigint not null references projects on delete cascade,
  title text not null,
  status varchar(20) not null default 'todo',
  assignee_id uuid references auth.users,
  created_at timestamptz not null default now(),
  check (status in ('todo', 'doing', 'done'))
);
alter table tasks enable row level security;
create index on tasks (project_id);

-- a view as the dashboard creates it: runs as its owner, so RLS on the tables does not bind it
create view project_overview as
  select p.id, p.name, t.name as team_name, count(k.id) as open_tasks
  from projects p join teams t on t.id = p.team_id
  left join tasks k on k.project_id = p.id and k.status <> 'done'
  group by p.id, p.name, t.name;

-- the usual helper for policies: runs as its owner
create function is_team_member(t bigint) returns boolean
  language sql stable security definer set search_path = public as
  $$ select exists (select 1 from team_members where team_id = t and user_id = auth.uid()) $$;
